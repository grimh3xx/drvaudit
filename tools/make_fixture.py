#!/usr/bin/env python3
"""Build tests/fixtures/linux-snapshot: a /proc + /sys + /lib/modules tree of
a compromised Linux host, used by docs/demo.svg.

  * e1000e, i915: signed in-tree modules
  * nvidia: signed out-of-tree DKMS module
  * vboxdrv: unsigned out-of-tree module
  * hid_logger: unsigned and force-loaded (taint F)
  * nf_conntrack_ext: loaded (sysfs kobject) but unlinked from /proc/modules

The .ko files are tiny stand-ins: an ELF magic, a body, and — for signed ones —
a CMS-like blob + struct module_signature + the appended-signature magic.
Usage: python3 tools/make_fixture.py
"""
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "fixtures" / "linux-snapshot"
REL = "6.8.0-45-generic"
MAGIC = b"~Module signature appended~\n"


def ko(name, signer=None):
    body = b"\x7fELF" + f" stand-in for {name}.ko ".encode() * 8
    if signer is None:
        return body
    cn = signer.encode()
    cms = bytes([0x30, 0x10, 0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x01])
    cms += bytes([0x06, 0x03, 0x55, 0x04, 0x03, 0x0C, len(cn)]) + cn
    return body + cms + bytes([0, 0, 2, 0, 0, 0, 0, 0]) + struct.pack(">I", len(cms)) + MAGIC


def w(rel, data):
    p = OUT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data if isinstance(data, bytes) else data.encode())


def main():
    w("proc/sys/kernel/osrelease", REL + "\n")
    mods = [
        ("e1000e", "kernel/drivers/net/ethernet/intel/e1000e/e1000e.ko", "Build time autogenerated kernel key", ""),
        ("i915", "kernel/drivers/gpu/drm/i915/i915.ko", "Build time autogenerated kernel key", ""),
        ("nvidia", "updates/dkms/nvidia.ko", "DKMS module signing key", " (PO)"),
        ("vboxdrv", "updates/dkms/vboxdrv.ko", None, " (OE)"),
        ("hid_logger", "extra/hid_logger.ko", None, " (OEF)"),
    ]
    dep, proc = [], []
    for name, rel, signer, taint in mods:
        w(f"lib/modules/{REL}/{rel}", ko(name, signer))
        dep.append(f"{rel}:")
        proc.append(f"{name} 61440 0 - Live 0x0000000000000000{taint}")
        w(f"sys/module/{name}/initstate", "live\n")
        if taint:
            w(f"sys/module/{name}/taint", taint.strip(" ()") + "\n")
    # Hidden: kobject present, list entry unlinked.
    w("sys/module/nf_conntrack_ext/initstate", "live\n")
    w(f"lib/modules/{REL}/modules.dep", "\n".join(dep) + "\n")
    w("proc/modules", "\n".join(proc) + "\n")
    # Built-in module: kobject without initstate (must not be flagged).
    (OUT / "sys/module/kernel/parameters").mkdir(parents=True, exist_ok=True)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
